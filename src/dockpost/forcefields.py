# ============================================================
# HELPERS
# ============================================================

def _normalize(
    value: str,
) -> str:

    return (
        str(
            value
        )
        .strip()
        .lower()
    )


def openmm_data_directory() -> Path:

    return (
        Path(
            app.__file__
        )
        .resolve()
        .parent
        / "data"
    )


def forcefield_xml_exists(
    xml: str,
) -> bool:

    return (
        openmm_data_directory()
        / xml
    ).exists()


# ============================================================
# PROTEIN RESOLUTION
# ============================================================

def resolve_protein_forcefield(
    name: str | None,
) -> ProteinForceFieldSpec:

    if name is None:

        name = (
            DEFAULT_PROTEIN_FORCEFIELD
        )


    key = _normalize(
        name
    )


    key = PROTEIN_ALIASES.get(
        key,
        key,
    )


    if key not in PROTEIN_FORCEFIELDS:

        choices = ", ".join(
            sorted(
                spec.name
                for spec
                in PROTEIN_FORCEFIELDS.values()
            )
        )


        raise ValueError(
            "Unsupported protein force field "
            f"'{name}'. Supported presets: {choices}"
        )


    spec = (
        PROTEIN_FORCEFIELDS[
            key
        ]
    )


    if not forcefield_xml_exists(
        spec.xml
    ):

        raise RuntimeError(
            "Required OpenMM force-field XML is not installed:\n"
            f"  {spec.xml}"
        )


    return spec


# ============================================================
# WATER RESOLUTION
# ============================================================

def resolve_water_model(
    name: str | None,
    protein_family: str,
) -> WaterModelSpec:

    if name is None:

        name = (
            DEFAULT_WATER_MODEL
        )


    key = _normalize(
        name
    )


    key = WATER_ALIASES.get(
        key,
        key,
    )


    if key not in WATER_MODELS:

        choices = ", ".join(
            sorted(
                WATER_MODELS
            )
        )


        raise ValueError(
            "Unsupported water model "
            f"'{name}'. Supported models: {choices}"
        )


    if protein_family not in {
        "amber14",
        "amber19",
    }:

        raise ValueError(
            "Amber water/ion presets currently require an "
            "Amber14 or Amber19 protein-family preset."
        )


    data = (
        WATER_MODELS[
            key
        ]
    )


    xml = (
        f"{protein_family}/{key}.xml"
    )


    if not forcefield_xml_exists(
        xml
    ):

        raise RuntimeError(
            "Required OpenMM water/ion XML is not installed:\n"
            f"  {xml}"
        )


    return WaterModelSpec(
        name=key,
        family=protein_family,
        xml=xml,
        modeller_model=(
            data[
                "modeller_model"
            ]
        ),
        sites=int(
            data[
                "sites"
            ]
        ),
    )


# ============================================================
# LIGAND RESOLUTION
# ============================================================

def installed_openff_forcefields() -> tuple[str, ...]:

    return tuple(
        SMIRNOFFTemplateGenerator
        .INSTALLED_FORCEFIELDS
    )


def installed_gaff_forcefields() -> tuple[str, ...]:

    return tuple(
        GAFFTemplateGenerator
        .INSTALLED_FORCEFIELDS
    )


def resolve_ligand_forcefield(
    name: str | None,
) -> LigandForceFieldSpec:

    if name is None:

        name = (
            DEFAULT_LIGAND_FORCEFIELD
        )


    key = _normalize(
        name
    )


    key = LIGAND_ALIASES.get(
        key,
        key,
    )


    openff_installed = {
        _normalize(
            value
        ):
        value

        for value
        in installed_openff_forcefields()
    }


    gaff_installed = {
        _normalize(
            value
        ):
        value

        for value
        in installed_gaff_forcefields()
    }


    if key in openff_installed:

        return LigandForceFieldSpec(
            name=(
                openff_installed[
                    key
                ]
            ),
            backend="smirnoff",
        )


    if key in gaff_installed:

        return LigandForceFieldSpec(
            name=(
                gaff_installed[
                    key
                ]
            ),
            backend="gaff",
        )


    all_installed = (
        sorted(
            openff_installed.values()
        )
        + sorted(
            gaff_installed.values()
        )
    )


    raise ValueError(
        "Ligand force field is not installed: "
        f"'{name}'.\n"
        "Installed ligand force fields:\n  "
        + "\n  ".join(
            all_installed
        )
    )


# ============================================================
# COMPLETE SELECTION
# ============================================================

def resolve_forcefield_selection(
    protein_forcefield: str | None = None,
    ligand_forcefield: str | None = None,
    water_model: str | None = None,
) -> ForceFieldSelection:

    protein = resolve_protein_forcefield(
        protein_forcefield
    )


    ligand = resolve_ligand_forcefield(
        ligand_forcefield
    )


    water = resolve_water_model(
        water_model,
        protein.family,
    )


    return ForceFieldSelection(
        protein=protein,
        ligand=ligand,
        water=water,
    )


# ============================================================
# FORCEFIELD CONSTRUCTION
# ============================================================

def register_ligand_template_generator(
    forcefield: ForceField,
    offmol,
    ligand_spec: LigandForceFieldSpec,
):

    if ligand_spec.backend == "smirnoff":

        generator = (
            SMIRNOFFTemplateGenerator(
                molecules=offmol,
                forcefield=(
                    ligand_spec.name
                ),
            )
        )


    elif ligand_spec.backend == "gaff":

        generator = (
            GAFFTemplateGenerator(
                molecules=offmol,
                forcefield=(
                    ligand_spec.name
                ),
            )
        )


    else:

        raise RuntimeError(
            "Internal error: unknown ligand force-field "
            f"backend '{ligand_spec.backend}'."
        )


    forcefield.registerTemplateGenerator(
        generator.generator
    )


    return generator


def create_forcefield(
    offmol,
    protein_forcefield: str | None = None,
    ligand_forcefield: str | None = None,
    water_model: str | None = None,
):

    selection = (
        resolve_forcefield_selection(
            protein_forcefield=(
                protein_forcefield
            ),
            ligand_forcefield=(
                ligand_forcefield
            ),
            water_model=(
                water_model
            ),
        )
    )


    forcefield = ForceField(
        *selection.xmls
    )


    generator = (
        register_ligand_template_generator(
            forcefield=forcefield,
            offmol=offmol,
            ligand_spec=(
                selection.ligand
            ),
        )
    )


    return (
        forcefield,
        selection,
        generator,
    )



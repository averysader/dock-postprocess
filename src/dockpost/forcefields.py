def available_forcefields_text() -> str:

    lines = []


    lines.append(
        "Protein presets:"
    )


    for spec in sorted(
        PROTEIN_FORCEFIELDS.values(),
        key=lambda value:
            value.name.lower(),
    ):

        lines.append(
            f"  {spec.name:12s}  {spec.xml}"
        )


    lines.append(
        ""
    )

    lines.append(
        "Water models:"
    )


    for name in sorted(
        WATER_MODELS
    ):

        lines.append(
            f"  {name}"
        )


    lines.append(
        ""
    )

    lines.append(
        "Installed OpenFF force fields:"
    )


    for name in (
        installed_openff_forcefields()
    ):

        lines.append(
            f"  {name}"
        )


    lines.append(
        ""
    )

    lines.append(
        "Installed GAFF force fields:"
    )


    for name in (
        installed_gaff_forcefields()
    ):

        lines.append(
            f"  {name}"
        )


    return "\n".join(
        lines
    )

#!/usr/bin/env python3

"""
Shared force-field configuration for dock-postprocess.

This module is intentionally used by both minimization and MD so that
protein, ligand, water, and ion parameterization cannot silently diverge
between simulation stages.

Supported protein presets
-------------------------
ff14SB
ff19SB
ff15ipq
amber14-all
amber19-all

Supported ligand backends
-------------------------
OpenFF/SMIRNOFF force fields installed through openmmforcefields
GAFF force fields installed through openmmforcefields

Supported Amber water/ion parameter sets
----------------------------------------
tip3p
tip3pfb
tip4pew
tip4pfb
spce
opc
opc3

The "modeller_model" associated with each water model controls only the
initial solvent topology generated by OpenMM Modeller.addSolvent().  The
requested XML file supplies the actual force-field parameters.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import re

import openmm.app as app

from openmm.app import ForceField

from openmmforcefields.generators import (
    GAFFTemplateGenerator,
    SMIRNOFFTemplateGenerator,
)


DEFAULT_PROTEIN_FORCEFIELD = "ff14SB"
DEFAULT_LIGAND_FORCEFIELD = "openff-2.3.0"
DEFAULT_WATER_MODEL = "tip3p"


# ============================================================
# DATA CLASSES
# ============================================================

@dataclass(frozen=True)
class ProteinForceFieldSpec:
    name: str
    xml: str
    family: str


@dataclass(frozen=True)
class WaterModelSpec:
    name: str
    family: str
    xml: str

    # Value accepted by Modeller.addSolvent(model=...).
    #
    # For parameter sets that use the same three-site or four-site
    # topology as one of OpenMM's built-in solvent builders, this is
    # the topology-building model only.  Parameters still come from
    # the requested XML above.
    modeller_model: str

    sites: int


@dataclass(frozen=True)
class LigandForceFieldSpec:
    name: str
    backend: str


@dataclass(frozen=True)
class ForceFieldSelection:
    protein: ProteinForceFieldSpec
    ligand: LigandForceFieldSpec
    water: WaterModelSpec

    @property
    def xmls(self) -> list[str]:

        return [
            self.protein.xml,
            self.water.xml,
        ]


